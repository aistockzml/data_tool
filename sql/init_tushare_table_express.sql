-- 接口名称：express_vip
-- 业绩快报
-- 主键：ID，唯一索引：(TS_CODE, END_DATE, ANN_DATE)
CREATE TABLE IF NOT EXISTS aistockzml_tushare_express (
    TS_CODE VARCHAR(20) COMMENT 'TS股票代码',
    ANN_DATE VARCHAR(20) COMMENT '公告日期',
    END_DATE VARCHAR(10) COMMENT '报告期',
    REVENUE DECIMAL(20,4) COMMENT '营业收入(元)',
    OPERATE_PROFIT DECIMAL(20,4) COMMENT '营业利润(元)',
    TOTAL_PROFIT DECIMAL(20,4) COMMENT '利润总额(元)',
    N_INCOME DECIMAL(20,4) COMMENT '净利润(元)',
    TOTAL_ASSETS DECIMAL(20,4) COMMENT '总资产(元)',
    TOTAL_HLDR_EQY_EXC_MIN_INT DECIMAL(20,4) COMMENT '股东权益合计(不含少数股东权益)(元)',
    DILUTED_EPS DECIMAL(20,4) COMMENT '每股收益(摊薄)(元)',
    DILUTED_ROE DECIMAL(20,4) COMMENT '净资产收益率(摊薄)(%)',
    YOY_NET_PROFIT DECIMAL(20,4) COMMENT '去年同期修正后净利润',
    BPS DECIMAL(20,4) COMMENT '每股净资产',
    YOY_SALES DECIMAL(20,4) COMMENT '同比增长率:营业收入',
    YOY_OP DECIMAL(20,4) COMMENT '同比增长率:营业利润',
    YOY_TP DECIMAL(20,4) COMMENT '同比增长率:利润总额',
    YOY_DEDU_NP DECIMAL(20,4) COMMENT '同比增长率:归属母公司股东的净利润',
    YOY_EPS DECIMAL(20,4) COMMENT '同比增长率:基本每股收益',
    YOY_ROE DECIMAL(20,4) COMMENT '同比增减:加权平均净资产收益率',
    GROWTH_ASSETS DECIMAL(20,4) COMMENT '比年初增长率:总资产',
    YOY_EQUITY DECIMAL(20,4) COMMENT '比年初增长率:归属母公司的股东权益',
    GROWTH_BPS DECIMAL(20,4) COMMENT '比年初增长率:归属于母公司股东的每股净资产',
    OR_LAST_YEAR DECIMAL(20,4) COMMENT '去年同期营业收入',
    OP_LAST_YEAR DECIMAL(20,4) COMMENT '去年同期营业利润',
    TP_LAST_YEAR DECIMAL(20,4) COMMENT '去年同期利润总额',
    NP_LAST_YEAR DECIMAL(20,4) COMMENT '去年同期净利润',
    EPS_LAST_YEAR DECIMAL(20,4) COMMENT '去年同期每股收益',
    OPEN_NET_ASSETS DECIMAL(20,4) COMMENT '期初净资产',
    OPEN_BPS DECIMAL(20,4) COMMENT '期初每股净资产',
    PERF_SUMMARY TEXT COMMENT '业绩简要说明',
    IS_AUDIT INT COMMENT '是否审计：1是 0否',
    REMARK TEXT COMMENT '备注',
    UPDATE_FLAG VARCHAR(10) COMMENT '更新标志',
    CREATE_BY VARCHAR(50) COMMENT '创建人',
    CREATE_TIME DATETIME COMMENT '创建时间',
    UPDATE_BY VARCHAR(50) COMMENT '更新人',
    UPDATE_TIME DATETIME COMMENT '更新时间',
    ID BIGINT PRIMARY KEY COMMENT '主键ID',
    ETL_TIME DATETIME COMMENT '数据加载时间',
    UNIQUE INDEX uk_ts_code_end_date_ann_date (TS_CODE, END_DATE, ANN_DATE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='业绩快报';
