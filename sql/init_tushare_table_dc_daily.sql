-- 接口名称：dc_daily
-- 东财概念板块行情
CREATE TABLE IF NOT EXISTS aistockzml_tushare_dc_daily (
    ID INT COMMENT '主键ID',
    TS_CODE VARCHAR(20) COMMENT '板块代码',
    TRADE_DATE VARCHAR(8) COMMENT '交易日',
    CATEGORY VARCHAR(20) COMMENT '板块类型',
    CLOSE DECIMAL(20,4) COMMENT '收盘点位',
    OPEN DECIMAL(20,4) COMMENT '开盘点位',
    HIGH DECIMAL(20,4) COMMENT '最高点位',
    LOW DECIMAL(20,4) COMMENT '最低点位',
    PRE_CLOSE DECIMAL(20,4) COMMENT '前收盘点位',
    `CHANGE` DECIMAL(20,4) COMMENT '涨跌点位',
    PCT_CHANGE DECIMAL(20,4) COMMENT '涨跌幅',
    VOL DECIMAL(20,4) COMMENT '成交量(股)',
    AMOUNT DECIMAL(20,4) COMMENT '成交额(元)',
    SWING DECIMAL(20,4) COMMENT '振幅',
    TURNOVER_RATE DECIMAL(20,4) COMMENT '换手率',
    AVG_PRICE DECIMAL(20,4) COMMENT '均价',
    PE_TTM DECIMAL(20,4) COMMENT '市盈率TTM',
    PB_MRQ DECIMAL(20,4) COMMENT '市净率MRQ',
    TOTAL_MV DECIMAL(20,4) COMMENT '总市值',
    FLOAT_MV DECIMAL(20,4) COMMENT '流通市值',
    CREATE_BY VARCHAR(50) COMMENT '创建人',
    CREATE_TIME DATETIME COMMENT '创建时间',
    UPDATE_BY VARCHAR(50) COMMENT '更新人',
    UPDATE_TIME DATETIME COMMENT '更新时间',
    etl_time DATETIME COMMENT '数据加载时间',
    PRIMARY KEY (ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='东财概念和行业指数行情';
